-- =========================================================
-- V1 - Estrutura inicial do banco do sistema de restaurante
-- PostgreSQL
-- =========================================================

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(180) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    perfil VARCHAR(20) NOT NULL
        CHECK (perfil IN ('GARCOM', 'COZINHA', 'GERENTE', 'ADMIN')),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- E-mail único sem diferenciar maiúsculas de minúsculas.
CREATE UNIQUE INDEX uq_usuarios_email_lower
    ON usuarios (LOWER(email));


CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    descricao TEXT,
    ativa BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uq_categorias_nome_lower
    ON categorias (LOWER(nome));


CREATE TABLE produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id BIGINT NOT NULL
        REFERENCES categorias(id) ON DELETE RESTRICT,
    nome VARCHAR(150) NOT NULL,
    descricao TEXT,
    preco NUMERIC(12, 2) NOT NULL CHECK (preco >= 0),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_produtos_categoria
    ON produtos(categoria_id);

CREATE INDEX idx_produtos_ativos
    ON produtos(ativo);


CREATE TABLE comandas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    qr_token UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    status VARCHAR(20) NOT NULL DEFAULT 'ABERTA'
        CHECK (status IN ('ABERTA', 'FECHADA', 'CANCELADA')),
    usuario_abertura_id BIGINT NOT NULL
        REFERENCES usuarios(id) ON DELETE RESTRICT,
    usuario_fechamento_id BIGINT
        REFERENCES usuarios(id) ON DELETE RESTRICT,
    aberta_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fechada_em TIMESTAMPTZ,
    observacao TEXT,
    CHECK (
        (status = 'ABERTA' AND fechada_em IS NULL)
        OR
        (status IN ('FECHADA', 'CANCELADA') AND fechada_em IS NOT NULL)
    )
);

CREATE INDEX idx_comandas_status_data
    ON comandas(status, aberta_em DESC);


CREATE TABLE pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comanda_id BIGINT NOT NULL
        REFERENCES comandas(id) ON DELETE RESTRICT,
    usuario_id BIGINT NOT NULL
        REFERENCES usuarios(id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'RECEBIDO'
        CHECK (status IN (
            'RECEBIDO',
            'EM_PREPARO',
            'PRONTO',
            'ENTREGUE',
            'CANCELADO'
        )),
    observacao TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    iniciado_em TIMESTAMPTZ,
    pronto_em TIMESTAMPTZ,
    entregue_em TIMESTAMPTZ
);

CREATE INDEX idx_pedidos_comanda
    ON pedidos(comanda_id);

CREATE INDEX idx_pedidos_cozinha
    ON pedidos(status, criado_em);


CREATE TABLE itens_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL
        REFERENCES pedidos(id) ON DELETE RESTRICT,
    produto_id BIGINT
        REFERENCES produtos(id) ON DELETE SET NULL,
    nome_produto VARCHAR(150) NOT NULL,
    preco_unitario NUMERIC(12, 2) NOT NULL
        CHECK (preco_unitario >= 0),
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'ATIVO'
        CHECK (status IN ('ATIVO', 'CANCELADO')),
    observacao TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_itens_pedido_pedido
    ON itens_pedido(pedido_id);

CREATE INDEX idx_itens_pedido_produto
    ON itens_pedido(produto_id);


CREATE TABLE pagamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comanda_id BIGINT NOT NULL
        REFERENCES comandas(id) ON DELETE RESTRICT,
    usuario_id BIGINT NOT NULL
        REFERENCES usuarios(id) ON DELETE RESTRICT,
    valor NUMERIC(12, 2) NOT NULL CHECK (valor > 0),
    forma_pagamento VARCHAR(30) NOT NULL
        CHECK (forma_pagamento IN (
            'DINHEIRO', 'PIX', 'CREDITO', 'DEBITO', 'OUTRO'
        )),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE'
        CHECK (status IN ('PENDENTE', 'CONFIRMADO', 'ESTORNADO')),
    referencia_externa VARCHAR(150),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    confirmado_em TIMESTAMPTZ
);

CREATE INDEX idx_pagamentos_comanda
    ON pagamentos(comanda_id);

CREATE INDEX idx_pagamentos_status
    ON pagamentos(status);


CREATE TABLE historico_comanda (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comanda_id BIGINT
        REFERENCES comandas(id) ON DELETE SET NULL,
    usuario_id BIGINT
        REFERENCES usuarios(id) ON DELETE SET NULL,
    acao VARCHAR(80) NOT NULL,
    detalhes JSONB NOT NULL DEFAULT '{}'::jsonb,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_historico_comanda_data
    ON historico_comanda(comanda_id, criado_em DESC);

CREATE INDEX idx_historico_criado_em
    ON historico_comanda(criado_em DESC);
